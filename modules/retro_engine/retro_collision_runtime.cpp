RetroCollisionRuntime::RetroCollisionRuntime() = default;

static Dictionary _retro_default_move(const String &p_state) {
	Dictionary m;
	m["state"] = p_state;
	m["damage"] = 0;
	m["hitstop_attacker"] = 0;
	m["hitstop_defender"] = 0;
	m["hitstun"] = 0;
	m["blockstun"] = 0;
	m["invuln"] = 0;
	m["guard"] = true;
	m["priority"] = 0;
	m["hit_id"] = 0;
	m["pushback"] = 0;
	return m;
}

void RetroCollisionRuntime::setup_from_animation(const Ref<RetroAnimation> &p_animation) {
	moves = Array();
	if (p_animation.is_null()) {
		return;
	}
	for (int i = 0; i < p_animation->get_states().size(); i++) {
		moves.push_back(_retro_default_move(String(p_animation->get_states().get_key_at_index(i))));
	}
}

void RetroCollisionRuntime::set_move(const String &p_state, const Dictionary &p_move) {
	for (int i = 0; i < moves.size(); i++) {
		Dictionary m = moves[i];
		if (String(m.get("state", "")) != p_state) {
			continue;
		}
		for (const Variant *K = p_move.next(nullptr); K; K = p_move.next(K)) {
			m[*K] = p_move[*K];
		}
		moves[i] = m;
		return;
	}
	Dictionary m = _retro_default_move(p_state);
	for (const Variant *K = p_move.next(nullptr); K; K = p_move.next(K)) {
		m[*K] = p_move[*K];
	}
	moves.push_back(m);
}

Dictionary RetroCollisionRuntime::get_move(const String &p_state) const {
	for (int i = 0; i < moves.size(); i++) {
		const Dictionary m = moves[i];
		if (String(m.get("state", "")) == p_state) {
			return m;
		}
	}
	return Dictionary();
}

void RetroCollisionRuntime::set_state_names(const Array &p_names) {
	state_names = p_names;
}

void RetroCollisionRuntime::apply_hitdef(const String &p_state, const Dictionary &p_hitdef) {
	Dictionary m = get_move(p_state);
	if (m.is_empty()) {
		m = _retro_default_move(p_state);
	}
	Dictionary d;
	d["damage"] = int(p_hitdef.get("damage", m.get("damage", 0)));
	d["hitstop_attacker"] = int(p_hitdef.get("hitstop_attacker", m.get("hitstop_attacker", 0)));
	d["hitstop_defender"] = int(p_hitdef.get("hitstop_defender", m.get("hitstop_defender", 0)));
	d["hitstun"] = int(p_hitdef.get("hitstun", m.get("hitstun", 0)));
	d["blockstun"] = int(p_hitdef.get("blockstun", m.get("blockstun", 0)));
	d["guard"] = String(p_hitdef.get("guardflag", "M")).strip_edges() != "";
	d["priority"] = int(m.get("priority", 0));
	d["invuln"] = int(m.get("invuln", 0));
	d["hitdef_state"] = int(p_hitdef.get("state", -1));
	d["hitdef_index"] = int(p_hitdef.get("index", -1));
	d["hit_id"] = int(p_hitdef.get("id", 0));
	if (p_hitdef.has("ground_velocity")) {
		d["pushback"] = abs(int(p_hitdef.get("ground_velocity", 0)));
	}
	set_move(p_state, d);
}

String RetroCollisionRuntime::generate_header(const String &p_platform) const {
	(void)p_platform;
	String out;
	out += "/* Generated by Godot Retro Engine collision runtime. */\n";
	out += "#ifndef RETRO_COLLISION_H\n#define RETRO_COLLISION_H\n\n";
	out += "typedef unsigned char retro_u8;\n";
	out += "typedef unsigned short retro_u16;\n";
	out += "typedef signed short retro_s16;\n\n";
	out += "#define RETRO_COL_STATE_COUNT " + itos(moves.size()) + "\n";
	out += "#define RETRO_COL_HIT 1\n";
	out += "#define RETRO_COL_HURT 0\n\n";
	out += "typedef struct { retro_u16 state, frame; retro_u8 type; retro_s16 x, y, w, h; } RetroColBox;\n";
	out += "typedef struct { retro_u16 state; retro_u16 damage; retro_u8 hitstop_attacker, hitstop_defender, hitstun, blockstun, invuln, guard, priority; retro_u16 hit_id; retro_s16 pushback; } RetroMove;\n";
	out += "typedef struct { retro_u16 state, frame; retro_s16 x, y; retro_u8 facing, hitstop, invuln, blocking; retro_s16 health; retro_u16 last_hit_id; } RetroFighter;\n";
	out += "typedef struct { retro_u8 contact, hit, blocked; retro_u16 damage; retro_u8 hitstop, hitstun, blockstun; retro_s16 x, y; } RetroHitResult;\n\n";
	out += "void retro_col_init(RetroFighter *fighter);\n";
	out += "void retro_col_tick(RetroFighter *fighter);\n";
	out += "retro_u8 retro_col_can_act(const RetroFighter *fighter);\n";
	out += "retro_u8 retro_col_check(const RetroFighter *attacker, const RetroFighter *defender, RetroHitResult *result);\n";
	out += "void retro_col_apply(RetroFighter *attacker, RetroFighter *defender, const RetroHitResult *result);\n";
	out += "const RetroMove *retro_col_move(retro_u16 state);\n";
	out += "const char *retro_col_state_name(retro_u16 state);\n\n#endif\n";
	return out;
}

String RetroCollisionRuntime::generate_source(const String &p_platform, const Ref<RetroAnimation> &p_animation) const {
	String out;
	out += "/* Generated by Godot Retro Engine collision runtime. */\n";
	out += "#include \"retro_collision.h\"\n\n";
	Array state_keys;
	Array boxes;
	if (p_animation.is_valid()) {
		state_keys = p_animation->get_states().keys();
	} else {
		for (int i = 0; i < moves.size(); i++) {
			state_keys.push_back(String(Dictionary(moves[i]).get("state", "")));
		}
	}
	if (p_animation.is_valid()) {
		state_keys = p_animation->get_states().keys();
		for (int sn = 0; sn < state_names.size(); sn++) {
			if (!state_keys.has(state_names[sn])) state_keys.push_back(state_names[sn]);
		}
		// MUGEN imports may add move profiles for states that have not been
		// imported into the animation document yet. Keep them in the table so
		// the generated state machine can reference them immediately.
		for (int m = 0; m < moves.size(); m++) {
			const String move_state = String(Dictionary(moves[m]).get("state", ""));
			if (!move_state.is_empty() && !state_keys.has(move_state)) {
				state_keys.push_back(move_state);
			}
		}
		for (int s = 0; s < state_keys.size(); s++) {
			const Dictionary st = p_animation->get_state(String(state_keys[s]));
			const Array frames = st.get("frames", Array());
			for (int f = 0; f < frames.size(); f++) {
				const Array hb = Dictionary(frames[f]).get("hitboxes", Array());
				for (int b = 0; b < hb.size(); b++) {
					const Dictionary box = hb[b];
					const Rect2i r = box.get("rect", Rect2i());
					Dictionary e;
					e["state"] = s;
					e["frame"] = f;
					e["type"] = String(box.get("type", "hit")) == "hurt" ? 0 : 1;
					e["x"] = r.position.x;
					e["y"] = r.position.y;
					e["w"] = r.size.x;
					e["h"] = r.size.y;
					boxes.push_back(e);
				}
			}
		}
	}
	out += "static const RetroColBox retro_boxes[" + itos(MAX(1, boxes.size())) + "] = {\n";
	for (int i = 0; i < boxes.size(); i++) {
		const Dictionary e = boxes[i];
		out += "\t{ " + itos(int(e.get("state", 0))) + ", " + itos(int(e.get("frame", 0))) + ", " + itos(int(e.get("type", 0))) + ", " +
				itos(int(e.get("x", 0))) + ", " + itos(int(e.get("y", 0))) + ", " + itos(int(e.get("w", 0))) + ", " + itos(int(e.get("h", 0))) + " },\n";
	}
	if (boxes.is_empty()) out += "\t{ 0, 0, 0, 0, 0, 0, 0 },\n";
	out += "};\n\n";
	out += "static const RetroMove retro_moves[" + itos(MAX(1, state_keys.size())) + "] = {\n";
	for (int i = 0; i < state_keys.size(); i++) {
		Dictionary m = get_move(String(state_keys[i]));
		if (m.is_empty()) {
			m = _retro_default_move(String(state_keys[i]));
		}
		out += "\t{ " + itos(i) + ", " + itos(int(m.get("damage", 0))) + ", " + itos(int(m.get("hitstop_attacker", 0))) + ", " +
				itos(int(m.get("hitstop_defender", 0))) + ", " + itos(int(m.get("hitstun", 0))) + ", " + itos(int(m.get("blockstun", 0))) + ", " +
				itos(int(m.get("invuln", 0))) + ", " + itos(bool(m.get("guard", true)) ? 1 : 0) + ", " + itos(int(m.get("priority", 0))) + ", " +
				itos(int(m.get("hit_id", 0))) + ", " + itos(int(m.get("pushback", 0))) + " },\n";
	}
	if (state_keys.is_empty()) out += "\t{ 0, 0, 0, 0, 0, 0, 0, 1, 0 },\n";
	out += "};\n\n";
	out += "static const char *retro_state_names[" + itos(MAX(1, state_keys.size())) + "] = {\n\t";
	for (int i = 0; i < state_keys.size(); i++) {
		if (i > 0) out += ", ";
		out += "\"" + String(state_keys[i]).replace("\"", "\\\"") + "\"";
	}
	if (state_keys.is_empty()) out += "\"\"";
	out += "\n};\n\n";
	out += "static const retro_u8 retro_guard_states[" + itos(MAX(1, state_keys.size())) + "] = {\n\t";
	for (int i = 0; i < state_keys.size(); i++) {
		const String sname = String(state_keys[i]).to_upper();
		const bool guard = sname.contains("BLOCK") || sname.contains("GUARD");
		if (i > 0) out += ", ";
		out += guard ? "1" : "0";
	}
	if (state_keys.is_empty()) out += "0";
	out += "\n};\n\n";
	out += "void retro_col_init(RetroFighter *f)\n{\n\tif (!f) return;\n\tf->state = 0; f->frame = 0; f->x = 0; f->y = 0; f->facing = 0; f->hitstop = 0; f->invuln = 0; f->blocking = 0; f->health = 100; f->last_hit_id = 0;\n}\n\n";
	out += "void retro_col_tick(RetroFighter *f)\n{\n\tif (!f) return;\n\tif (f->hitstop > 0) f->hitstop--;\n\tif (f->invuln > 0) f->invuln--;\n}\n\n";
	out += "retro_u8 retro_col_can_act(const RetroFighter *f) { return (!f || f->hitstop == 0) ? 1 : 0; }\n\n";
	out += "const RetroMove *retro_col_move(retro_u16 state)\n{\n\tif (state >= " + itos(MAX(1, state_keys.size())) + ") return &retro_moves[0];\n\treturn &retro_moves[state];\n}\n\n";
	out += "const char *retro_col_state_name(retro_u16 state) { return state < " + itos(MAX(1, state_keys.size())) + " ? retro_state_names[state] : \"?\"; }\n\n";
	out += "retro_u8 retro_col_check(const RetroFighter *a, const RetroFighter *b, RetroHitResult *out)\n{\n";
	out += "\tretro_u16 i, j;\n\tretro_u8 blocking;\n\tretro_s16 ax, ay, bx, by;\n\tconst RetroMove *move;\n";
	out += "\tif (!a || !b || !out) return 0;\n";
	out += "\tout->contact = 0; out->hit = 0; out->blocked = 0; out->damage = 0;\n";
	out += "\tif (b->invuln > 0) return 0;\n";
	out += "\tmove = retro_col_move(a->state);\n";
	out += "\tif (move->hit_id != 0 && b->last_hit_id == move->hit_id) return 0;\n";
	out += "\tfor (i = 0; i < " + itos(MAX(1, boxes.size())) + "; i++)\n\t{\n";
	out += "\t\tif (i >= " + itos(boxes.size()) + ") break;\n";
	out += "\t\tif (retro_boxes[i].state != a->state || retro_boxes[i].frame != a->frame || retro_boxes[i].type != RETRO_COL_HIT) continue;\n";
	out += "\t\tax = (retro_s16)(a->facing ? a->x - retro_boxes[i].x - retro_boxes[i].w : a->x + retro_boxes[i].x);\n";
	out += "\t\tay = (retro_s16)(a->y + retro_boxes[i].y);\n";
	out += "\t\tfor (j = 0; j < " + itos(MAX(1, boxes.size())) + "; j++)\n\t\t{\n";
	out += "\t\t\tif (j >= " + itos(boxes.size()) + ") break;\n";
	out += "\t\t\tif (retro_boxes[j].state != b->state || retro_boxes[j].frame != b->frame || retro_boxes[j].type != RETRO_COL_HURT) continue;\n";
	out += "\t\t\tbx = (retro_s16)(b->facing ? b->x - retro_boxes[j].x - retro_boxes[j].w : b->x + retro_boxes[j].x);\n";
	out += "\t\t\tby = (retro_s16)(b->y + retro_boxes[j].y);\n";
	out += "\t\t\tif (ax < bx + retro_boxes[j].w && ax + retro_boxes[i].w > bx && ay < by + retro_boxes[j].h && ay + retro_boxes[i].h > by)\n\t\t\t{\n";
	out += "\t\t\t\tout->contact = 1;\n";
	out += "\t\t\t\tblocking = b->blocking;\n";
	out += "\t\t\t\tif (!blocking && b->state < " + itos(MAX(1, state_keys.size())) + ") blocking = retro_guard_states[b->state];\n";
	out += "\t\t\t\tout->blocked = (retro_u8)(blocking && move->guard);\n";
	out += "\t\t\t\tout->hit = out->blocked ? 0 : 1;\n";
	out += "\t\t\t\tout->damage = out->blocked ? 0 : move->damage;\n";
	out += "\t\t\t\tout->hitstop = out->blocked ? move->blockstun : move->hitstop_defender;\n";
	out += "\t\t\t\tout->hitstun = out->blocked ? 0 : move->hitstun;\n\t\t\t\tout->blockstun = move->blockstun;\n";
	out += "\t\t\t\tout->x = ax; out->y = ay;\n\t\t\t\treturn 1;\n\t\t\t}\n\t\t}\n\t}\n\treturn 0;\n}\n\n";
	out += "void retro_col_apply(RetroFighter *a, RetroFighter *b, const RetroHitResult *r)\n{\n";
	out += "\tconst RetroMove *move;\n\tif (!a || !b || !r || !r->contact) return;\n";
	out += "\tmove = retro_col_move(a->state);\n";
	out += "\ta->hitstop = move->hitstop_attacker;\n";
	out += "\tif (r->blocked) { b->hitstop = move->blockstun; b->blocking = 1; }\n";
	out += "\telse { b->health = (retro_s16)(b->health - r->damage); b->hitstop = move->hitstop_defender; b->invuln = move->invuln; b->last_hit_id = move->hit_id; }\n";
	out += "\tif (move->pushback != 0) b->x = (retro_s16)(b->x + (a->facing ? -move->pushback : move->pushback));\n";
	out += "}\n";
	return out;
}

Dictionary RetroCollisionRuntime::export_snes(const String &p_dir, const String &p_base, const Ref<RetroAnimation> &p_animation) {
	DirAccess::make_dir_recursive_absolute(p_dir);
	const String h = RetroUtil::join(p_dir, p_base + ".h");
	const String c = RetroUtil::join(p_dir, p_base + ".c");
	const Error e1 = RetroUtil::write_text(h, generate_header("snes"));
	const Error e2 = RetroUtil::write_text(c, generate_source("snes", p_animation));
	Dictionary out;
	out["ok"] = e1 == OK && e2 == OK;
	out["header"] = h;
	out["source"] = c;
	return out;
}

Dictionary RetroCollisionRuntime::export_sgdk(const String &p_dir, const String &p_base, const Ref<RetroAnimation> &p_animation) {
	DirAccess::make_dir_recursive_absolute(p_dir);
	const String h = RetroUtil::join(p_dir, p_base + ".h");
	const String c = RetroUtil::join(p_dir, p_base + ".c");
	const Error e1 = RetroUtil::write_text(h, generate_header("megadrive"));
	const Error e2 = RetroUtil::write_text(c, generate_source("megadrive", p_animation));
	Dictionary out;
	out["ok"] = e1 == OK && e2 == OK;
	out["header"] = h;
	out["source"] = c;
	return out;
}

Error RetroCollisionRuntime::save(const String &p_path) const {
	return RetroUtil::save_json_file(p_path, to_dict());
}

Error RetroCollisionRuntime::load(const String &p_path) {
	bool ok = false;
	const Dictionary d = RetroUtil::parse_json_file(p_path, &ok);
	if (!ok) {
		return ERR_FILE_CANT_READ;
	}
	from_dict(d);
	return OK;
}

Dictionary RetroCollisionRuntime::to_dict() const {
	Dictionary d;
	d["format"] = "godot-retro-engine/collision-runtime";
	d["version"] = 1;
	d["platform"] = platform;
	d["moves"] = moves;
	d["metadata"] = metadata;
	return d;
}

void RetroCollisionRuntime::from_dict(const Dictionary &p_data) {
	platform = p_data.get("platform", platform);
	moves = p_data.get("moves", moves);
	metadata = p_data.get("metadata", metadata);
}
