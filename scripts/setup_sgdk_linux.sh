#!/usr/bin/env bash
# Prepare a working SGDK 2.11 Linux toolchain using:
#   * the GCC 13.2 m68k-elf toolchain shipped in SGDK's bin/ (run through Wine)
#   * native Linux builds of sjasm, convsym and bintos from $SGDK/tools
#
# Usage:
#   SGDK_ROOT=/path/to/sgdk211 scripts/setup_sgdk_linux.sh
#   source vendor/sgdk-linux/env.sh
#   scripts/run_linux.sh
#
# The IDE detects m68k-elf-gcc through PATH, so launch it from a shell that
# sourced env.sh (or add vendor/sgdk-linux/bin to PATH yourself).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SGDK_ROOT="${SGDK_ROOT:-/run/media/fabio/Dados/Fabio/sgdk211}"
OUT="$ROOT/vendor/sgdk-linux"
BIN="$OUT/bin"
SRC="$OUT/src"

if [ ! -x "$SGDK_ROOT/bin/gcc.exe" ]; then
  echo "SGDK not found at $SGDK_ROOT (expected bin/gcc.exe)." >&2
  exit 1
fi
if ! command -v wine >/dev/null 2>&1; then
  echo "Wine is required for SGDK's Windows m68k-elf GCC 13.2 binaries." >&2
  echo "Install wine (e.g. sudo apt install wine64) or provide a native m68k-elf toolchain." >&2
  exit 1
fi
SGDK_ROOT="$(cd "$SGDK_ROOT" && pwd)"

mkdir -p "$BIN" "$SRC"

echo "==> Building host tools (sjasm, convsym, bintos)"
rm -rf "$SRC/sjasm" "$SRC/convsym"
cp -a "$SGDK_ROOT/tools/sjasm/src" "$SRC/sjasm"
cp -a "$SGDK_ROOT/tools/convsym" "$SRC/convsym"
make -C "$SRC/sjasm" -j"$(nproc)" >/dev/null
make -C "$SRC/convsym" -j"$(nproc)" >/dev/null
gcc -O2 -o "$BIN/bintos" "$SGDK_ROOT/tools/bintos/src/bintos.c"
cp "$SRC/sjasm/sjasm" "$BIN/sjasm"
cp "$SRC/convsym/build/convsym" "$BIN/convsym"

echo "==> Generating Wine path-conversion wrappers"
cat > "$BIN/_wine_common.py" <<'PYEOF'
import os
import sys

SGDK = os.environ.get("RETRO_SGDK_ROOT", "")


def to_win(path: str) -> str:
    if path.startswith("/"):
        return "Z:" + path.replace("/", "\\")
    return path


def run(tool: str, args, env_extra=None):
    exe = os.path.join(SGDK, "bin", tool + ".exe")
    env = dict(os.environ)
    env["WINEDEBUG"] = "-all"
    if env_extra:
        env.update(env_extra)
    os.execvpe("wine", ["wine", exe] + list(args), env)
PYEOF

cat > "$BIN/m68k-elf-gcc" <<'PYEOF'
#!/usr/bin/env python3
import os
import sys
sys.path.insert(0, os.path.dirname(__file__))
import _wine_common as W

args = []
for a in sys.argv[1:]:
    # Wine writes .d files with Windows drive paths; make cannot parse those.
    # Dependency generation is therefore left to the host makefile timestamps.
    if a in ("-MMD", "-MD", "-MP"):
        continue
    if a.startswith("/"):
        a = W.to_win(a)
    elif a.startswith("@"):
        a = "@" + W.to_win(a[1:])
    else:
        for pre in ("-B", "-I", "-L", "-T", "-o", "-MF", "-MT", "-include", "-isystem", "-iquote", "-idirafter"):
            if a.startswith(pre) and len(a) > len(pre) and a[len(pre)] == "/":
                val = W.to_win(a[len(pre):])
                if pre == "-B":
                    val = val.rstrip("\\") + "\\"
                a = pre + val
                break
    args.append(a)
W.run("gcc", args)
PYEOF

for tool in ar as ld nm objcopy objdump ranlib strip; do
cat > "$BIN/m68k-elf-$tool" <<PYEOF
#!/usr/bin/env python3
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import _wine_common as W
W.run("$tool", [W.to_win(a) for a in sys.argv[1:]])
PYEOF
done
chmod +x "$BIN"/*
# The helper imports RETRO_SGDK_ROOT at runtime.
cat > "$BIN/_wine_common.py" <<'PYEOF'
import os
import sys

SGDK = os.environ.get("RETRO_SGDK_ROOT", "")


def to_win(path: str) -> str:
    if path.startswith("/"):
        return "Z:" + path.replace("/", "\\")
    return path


def run(tool: str, args, env_extra=None):
    if not SGDK:
        raise SystemExit("RETRO_SGDK_ROOT is not set; source vendor/sgdk-linux/env.sh")
    exe = os.path.join(SGDK, "bin", tool + ".exe")
    env = dict(os.environ)
    env["WINEDEBUG"] = "-all"
    if env_extra:
        env.update(env_extra)
    os.execvpe("wine", ["wine", exe] + list(args), env)
PYEOF

cat > "$OUT/env.sh" <<EOF
# Generated by scripts/setup_sgdk_linux.sh
export RETRO_SGDK_ROOT="$SGDK_ROOT"
export GDK="$SGDK_ROOT"
export PATH="$BIN:\$PATH"
EOF

echo "==> Smoke test (SGDK sample copied under $OUT/test)"
rm -rf "$OUT/test"
cp -a "$SGDK_ROOT/sample/basics/image" "$OUT/test"
cat > "$OUT/test/Makefile" <<EOF
GDK = $SGDK_ROOT
include \$(GDK)/makefile.gen
EOF
(
  cd "$OUT/test"
  export RETRO_SGDK_ROOT="$SGDK_ROOT"
  export PATH="$BIN:$PATH"
  make clean >/dev/null 2>&1 || true
  make -j1 LIBGCC="$SGDK_ROOT/lib/libgcc.a" >/dev/null
)
file "$OUT/test/out/rom.bin" 2>/dev/null || true

cat <<EOF
==> SGDK Linux toolchain ready.
    source $OUT/env.sh
    Then launch the IDE from that shell:
      scripts/run_linux.sh
EOF
